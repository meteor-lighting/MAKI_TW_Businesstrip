create or replace function public.resolve_login(identifier text)
returns table(email text, must_reset_password boolean)
language sql stable security definer set search_path = public
as $$
  select p.email::text, p.must_reset_password
  from public.profile_login_aliases a
  join public.profiles p on p.id = a.user_id
  where lower(a.alias::text) = lower(trim(identifier))
  union all
  select p.email::text, p.must_reset_password
  from public.profiles p
  where lower(p.email::text) = lower(trim(identifier))
    and not exists (
      select 1 from public.profile_login_aliases a
      where lower(a.alias::text) = lower(trim(identifier))
    )
  limit 1
$$;
grant execute on function public.resolve_login(text) to anon, authenticated;

