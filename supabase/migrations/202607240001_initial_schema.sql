create or replace function public.delete_report(target_report_id text)
returns void language plpgsql security definer set search_path = public
as $$
declare target public.reports;
begin
  select * into target from public.reports where id = target_report_id for update;
  if target.id is null then return; end if;
  if target.status <> '' then raise exception 'Cannot delete a report with an existing status'; end if;
  if target.owner_id <> auth.uid() and not public.is_admin() then raise exception 'Permission denied'; end if;
  delete from public.reports where id = target_report_id;
end;
$$;
grant execute on function public.delete_report(text) to authenticated;

create or replace function public.copy_report(source_report_id text)
returns text language plpgsql security definer set search_path = public
as $$
declare source public.reports; profile public.profiles; new_id text;
begin
  select * into source from public.reports where id = source_report_id;
  select * into profile from public.profiles where id = auth.uid();
  if source.id is null or profile.id is null then raise exception 'Source report or profile not found'; end if;
  if source.owner_id <> auth.uid() and not (profile.role = 'admin' or profile.can_copy_others) then
    raise exception 'Permission denied';
  end if;
  new_id := 'BR-' || lpad(nextval('public.report_number_seq')::text, 8, '0');
  insert into public.reports (id, owner_id, report_name, days, start_date, end_date, destination, payment_currency, data)
  values (
    new_id, auth.uid(), source.report_name || ' (複製)', source.days, source.start_date, source.end_date,
    source.destination, source.payment_currency,
    source.data || jsonb_build_object('報告編號', new_id, '用戶編號', profile.employee_code, '員工姓名', profile.display_name,
      '報告名稱', source.report_name || ' (複製)', '狀態', '')
  );
  insert into public.expense_items (report_id, category, sequence, data)
  select new_id, category, sequence, data || jsonb_build_object('報告編號', new_id)
  from public.expense_items where report_id = source_report_id;
  perform public.recalculate_report(new_id);
  return new_id;
end;
$$;
grant execute on function public.copy_report(text) to authenticated;

create or replace function public.copy_items(target_report_id text, source_item_ids uuid[])
returns integer language plpgsql security definer set search_path = public
as $$
declare source record; seq integer; copied integer := 0;
begin
  if not public.can_edit_report(target_report_id) then raise exception 'Report is locked or you cannot edit it'; end if;
  perform 1 from public.reports where id = target_report_id for update;
  for source in
    select * from public.expense_items where id = any(source_item_ids) and public.can_view_report(report_id)
  loop
    select coalesce(max(sequence), 0) + 1 into seq
    from public.expense_items where report_id = target_report_id and category = source.category;
    insert into public.expense_items (report_id, category, sequence, data)
    values (target_report_id, source.category, seq, source.data || jsonb_build_object('報告編號', target_report_id, '次序', seq));
    copied := copied + 1;
  end loop;
  perform public.recalculate_report(target_report_id);
  return copied;
end;
$$;
grant execute on function public.copy_items(text,uuid[]) to authenticated;

create or replace function public.sync_report_sequence()
returns bigint language plpgsql security definer set search_path = public
as $$
declare maximum bigint;
begin
  select coalesce(max(substring(id from 4)::bigint), 0) into maximum from public.reports;
  perform setval('public.report_number_seq', greatest(maximum, 1), maximum > 0);
  return maximum;
end;
$$;

