create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  code text;
  label text;
begin
  code := coalesce(nullif(new.raw_user_meta_data ->> 'employee_code', ''), 'U-' || substr(new.id::text, 1, 8));
  label := coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(new.email, '@', 1));
  insert into public.profiles (id, employee_code, display_name, email)
  values (new.id, code, label, new.email)
  on conflict (id) do nothing;
  insert into public.profile_login_aliases (alias, user_id)
  values (code, new.id), (label, new.id)
  on conflict (alias) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
